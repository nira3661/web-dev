    /* ============================================================
       RANDOMIZED WRITERS PLAYLIST (Shuffled Deck / No Immediate Repeats)
       ============================================================ */
    let playlist = [];
    let playlistCursor = 0;
    let currentIndex = 0;

    function generateShuffledPlaylist(previousLastIndex = -1) {
      const indices = Array.from({ length: writers.length }, (_, i) => i);
      // Fisher-Yates shuffle
      for (let i = indices.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [indices[i], indices[j]] = [indices[j], indices[i]];
      }
      // Guarantee the first piece in a new cycle never duplicates the last piece of previous cycle
      if (indices.length > 1 && indices[0] === previousLastIndex) {
        const swapTarget = 1 + Math.floor(Math.random() * (indices.length - 1));
        [indices[0], indices[swapTarget]] = [indices[swapTarget], indices[0]];
      }
      return indices;
    }

    function initPlaylist() {
      playlist = generateShuffledPlaylist();
      playlistCursor = 0;
      currentIndex = playlist[0];
    }

    function getNextWriterIndex() {
      playlistCursor++;
      if (playlistCursor >= playlist.length) {
        const lastPlayed = playlist[playlist.length - 1];
        playlist = generateShuffledPlaylist(lastPlayed);
        playlistCursor = 0;
      }
      return playlist[playlistCursor];
    }

