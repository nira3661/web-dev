    let holdStart = null;
    let isHolding = false;
    let holdTarget = null; // 'launch', 'switch', or 'overlaySwitch'

    function startHold(target) {
      if (isHolding) return;
      isHolding = true;
      holdTarget = target;
      holdStart = performance.now();
      document.body.classList.add('holding');
      animateHold();
    }

    function endHold() {
      if (!isHolding) return;
      isHolding = false;
      document.body.classList.remove('holding');
      cancelAnimationFrame(spaceAnimFrame);

      if (holdTarget === 'launch' && spaceProgress >= 100) {
        launchRecall();
      } else if (holdTarget === 'switch' && spaceProgress >= 100) {
        switchWriter();
      } else {
        springBack();
      }
      holdTarget = null;
      holdStart = null;
    }

    function animateHold() {
      if (!isHolding || !holdStart) return;
      const elapsed = performance.now() - holdStart;
      spaceProgress = Math.min(100, (elapsed / SPACE_HOLD_DURATION) * 100);
      updateFill();
      if (spaceProgress < 100) {
        spaceAnimFrame = requestAnimationFrame(animateHold);
      }
    }

    function updateFill() {
      const launchFill = document.getElementById('launchFill');
      const spaceFill = document.getElementById('spaceFill');
      if (launchFill) launchFill.style.width = spaceProgress + '%';
      if (spaceFill) spaceFill.style.width = spaceProgress + '%';
    }

    function resetFills() {
      spaceProgress = 0;
      updateFill();
    }

    function springBack() {
      const duration = 350;
      const start = performance.now();
      const from = spaceProgress;
      function anim(now) {
        const t = Math.min(1, (now - start) / duration);
        const eased = 1 - Math.pow(1 - t, 3);
        spaceProgress = from * (1 - eased);
        updateFill();
        if (t < 1) {
          requestAnimationFrame(anim);
        } else {
          document.body.classList.remove('holding');
        }
      }
      requestAnimationFrame(anim);
    }

